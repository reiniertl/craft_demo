function generateIndexUpdate(spec: ShimSpec): string {
  const simpleName = spec.className.split('.').pop()!;
  const relativePath = classNameToPath(spec.className);

  return `
// Add this to the appropriate index.ts file:
import { register${simpleName}Shim } from './${relativePath.split('/').pop()?.replace('.ts', '')}';

// In the registration function:
register${simpleName}Shim(registry);
`;
}

function writeShimFiles(spec: ShimSpec): void {
  const basePath = path.join(__dirname, '..', 'src', 'shim');
  const relativePath = classNameToPath(spec.className);
  const fullPath = path.join(basePath, relativePath);
  const testPath = path.join(__dirname, '..', 'test', 'unit', 'shim', relativePath);

  // Create directories
  const dir = path.dirname(fullPath);
  const testDir = path.dirname(testPath);

  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  if (!fs.existsSync(testDir)) {
    fs.mkdirSync(testDir, { recursive: true });
  }

  // Write shim file
  const shimCode = generateShimCode(spec);
  fs.writeFileSync(fullPath, shimCode);
  console.log(`[CRAFT][GenShim][Success] Created shim: ${fullPath}`);

  // Write test file
  const testCode = generateTestCode(spec);
  fs.writeFileSync(testPath, testCode);
  console.log(`[CRAFT][GenShim][Success] Created test: ${testPath}`);

  // Print index update instructions
  console.log('\n[CRAFT][GenShim][Info] Update index.ts:');
  console.log(generateIndexUpdate(spec));
}

function parseMethodSpec(spec: string): MethodSpec {
  // Format: name:descriptor:returnType
  const parts = spec.split(':');
  if (parts.length !== 3) {
    throw new Error(`Invalid method spec: ${spec}`);
  }

  return {
    name: parts[0],
    descriptor: parts[1],
    returnType: parts[2],
    params: [] // TODO: Parse from descriptor
  };
}

function parseFieldSpec(spec: string): FieldSpec {
  // Format: name:type
  const parts = spec.split(':');
  if (parts.length !== 2) {
    throw new Error(`Invalid field spec: ${spec}`);
  }

  return {
    name: parts[0],
    type: parts[1]
  };
}

function main() {
  const args = process.argv.slice(2);

  if (args.length === 0 || args.includes('--help')) {
    printUsage();
    process.exit(0);
  }

  const className = args[0];
  const spec: ShimSpec = {
    className,
    methods: [],
    fields: []
  };

  for (let i = 1; i < args.length; i++) {
    switch (args[i]) {
      case '--method':
        spec.methods.push(parseMethodSpec(args[++i]));
        break;
      case '--extends':
        spec.extends = args[++i];
        break;
      case '--field':
        spec.fields!.push(parseFieldSpec(args[++i]));
        break;
      case '--interactive':
        console.log('[CRAFT][GenShim][Info] Interactive mode not yet implemented');
        break;
    }
  }

  console.log(`[CRAFT][GenShim][Info] Generating shim for ${className}`);
  writeShimFiles(spec);
  console.log('[CRAFT][GenShim][Success] Shim generation complete! ✅');
}

main();
