#!/usr/bin/env ts-node
/**
 * CRAFT Shim Generator - Skill #2
 * Generate Android API shim implementations with boilerplate code
 */

import * as fs from 'fs';
import * as path from 'path';

interface ShimSpec {
  className: string;      // e.g., "android.graphics.Paint"
  methods: MethodSpec[];
  extends?: string;       // Parent class
  fields?: FieldSpec[];
}

interface MethodSpec {
  name: string;
  descriptor: string;
  returnType: string;
  params: string[];
  isStatic?: boolean;
}

interface FieldSpec {
  name: string;
  type: string;
  isStatic?: boolean;
}

function printUsage() {
  console.log(`
CRAFT Shim Generator

Usage: npx ts-node tools/gen_shim.ts <class-name> [options]

Arguments:
  <class-name>          Full Android class name (e.g., android.graphics.Paint)

Options:
  --method <spec>       Add method (format: name:descriptor:returnType)
  --extends <class>     Parent class name
  --field <spec>        Add field (format: name:type)
  --interactive         Interactive mode (prompts for details)
  --help               Show this help message

Examples:
  # Generate basic shim
  npx ts-node tools/gen_shim.ts android.graphics.Paint

  # With methods and parent class
  npx ts-node tools/gen_shim.ts android.graphics.Paint \\
    --extends android.view.View \\
    --method "setColor:(I)V:void" \\
    --method "getColor:()I:number"

  # Interactive mode
  npx ts-node tools/gen_shim.ts android.graphics.Paint --interactive
`);
}

function classNameToPath(className: string): string {
  // Convert android.graphics.Paint to android/graphics/paint.ts
  return className.replace(/\./g, '/').toLowerCase() + '.ts';
}

function classNameToDescriptor(className: string): string {
  // Convert android.graphics.Paint to Landroid/graphics/Paint;
  return 'L' + className.replace(/\./g, '/') + ';';
}

function generateShimCode(spec: ShimSpec): string {
  const descriptor = classNameToDescriptor(spec.className);
  const simpleName = spec.className.split('.').pop()!;
  const extendsDescriptor = spec.extends ? classNameToDescriptor(spec.extends) : 'Ljava/lang/Object;';

  const code = `/**
 * Shim for ${spec.className}
 * Generated by CRAFT Shim Generator
 */

import { ShimRegistry } from '../../interpreter/shim_registry';
import { Heap } from '../../interpreter/heap';
import { Interpreter } from '../../interpreter/interpreter';
import { Value } from '../../core/types';
import { log } from '../../core/utils';

export const ${simpleName.toUpperCase()}_CLASS = '${descriptor}';

/**
 * Register ${simpleName} shim methods
 */
export function register${simpleName}Shim(registry: ShimRegistry): void {
  log('shim', 'info', \`Registering ${simpleName} shim\`);

  // Constructor
  registry.register(
    ${simpleName.toUpperCase()}_CLASS,
    '<init>',
    '()V',
    (interp: Interpreter, heap: Heap, thisRef: number, args: Value[]): Value => {
      log('shim', 'debug', \`${simpleName}.<init>()\`);

      // Call parent constructor
      const parentConstructor = registry.getMethod('${extendsDescriptor}', '<init>', '()V');
      if (parentConstructor) {
        parentConstructor(interp, heap, thisRef, args);
      }

      // Initialize fields${spec.fields ? '\n' + spec.fields.map(f =>
        `      heap.setField(thisRef, '${f.name}', { type: '${getValueType(f.type)}', value: ${getDefaultValue(f.type)} });`
      ).join('\n') : ''}

      return { type: 'null' };
    }
  );

${spec.methods.map(method => generateMethodShim(simpleName, method)).join('\n\n')}
}

${spec.fields && spec.fields.length > 0 ? `
/**
 * ${simpleName} field definitions
 */
interface ${simpleName}Fields {
${spec.fields.map(f => `  ${f.name}: ${f.type};`).join('\n')}
}
` : ''}
`;

  return code;
}

function generateMethodShim(className: string, method: MethodSpec): string {
  const paramList = method.params.map((p, i) => `args[${i}]`).join(', ');

  return `  // ${method.name}${method.descriptor}
  registry.register(
    ${className.toUpperCase()}_CLASS,
    '${method.name}',
    '${method.descriptor}',
    (interp: Interpreter, heap: Heap, thisRef: number, args: Value[]): Value => {
      log('shim', 'debug', \`${className}.${method.name}()\`);

      // TODO: Implement ${method.name} logic
      ${method.returnType === 'void' ?
        'return { type: \'null\' };' :
        `return { type: '${getValueType(method.returnType)}', value: ${getDefaultValue(method.returnType)} };`
      }
    }
  );`;
}

function getValueType(type: string): string {
  if (type.includes('int') || type === 'boolean' || type === 'byte' || type === 'short' || type === 'char') {
    return 'int';
  }
  if (type === 'long') return 'long';
  if (type === 'float') return 'float';
  if (type === 'double') return 'double';
  return 'object';
}

function getDefaultValue(type: string): string {
  if (type.includes('int') || type === 'boolean') return '0';
  if (type === 'long') return '0n';
  if (type === 'float' || type === 'double') return '0.0';
  return '0';
}

